/*
问题描述
小明在出差结束后返回了公司所在的城市，在填写差旅报销申请时，粗心的小明发现自己弄丢了出差过程中的票据。

为了弥补小明的损失，公司同意小明用别的票据进行报销，但是公司财务要求小明提交的票据中任意两张的日期差不小于 K 天，
且总金额不得超过实际差旅费用 M。

比如财务要求 K = 7 时，若小明提交了一张 1 月 8 日的票据，小明就不能提交 1 月 2 日至 1 月 14 日之间的其他票据，
1 月 1 日及之前和 1 月 15 日及之后的票据则可以提交。

公司的同事们一起给小明凑了 N 张票据，小明现在想要请你帮他整理一下，从中选取出符合财务要求的票据，并使总金额尽可能接近 M。

需要注意，由于这些票据都是同一年的，因此 12 月底的票据不会影响到 1 月初票据的提交。这一年不是闰年。

输入格式
第 1 行：3 个整数 N, M, K。
第 2...N+1 行：每行 3 个整数 m_i, d_i, v_i，第 i+1 行表示第 i 张票据时间的月份 m_i 和日期 d_i，v_i 表示该票据的面值。

输出格式
第 1 行：1 个整数，表示小明能够凑出的最大报销金额。

样例输入
4 16 3
1 1 1
1 3 2
1 4 4
1 6 8

样例输出
10

样例说明
选择 1 月 3 日和 1 月 6 日的票据。

评测用例规模与约定
对于 100% 的评测用例：1 <= N <= 1000，1 <= M <= 5000，1 <= K <= 50，
1 <= m_i <= 12，1 <= d_i <= 31，1 <= v_i <= 400。日期保证合法。

运行限制
最大运行时间：1s
最大运行内存：512M
*/

#include<bits/stdc++.h>
using namespace std;

int main() {
	int N, M, K;  cin>>N>>M>>K;
	int days[] = {0, 31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31};
	vector<int> prefix(13);  prefix[0] = 0;
	// 预计算前缀和天数
	for(int i = 1; i <= 12; i++) {
		prefix[i] = prefix[i-1] + days[i-1];
	}
	vector<int> tickets[366]; // 记录第 d 天的票据面值
	for(int i = 0; i < N; i++) {
		int m, d, v;  cin>>m>>d>>v;
		// 把月和日映射到 绝对天数
		int abs_day = prefix[m] + d;
		tickets[abs_day].push_back(v);
	}
	// dp[d][j] 表示前 d 天，总金额不超过 j 的最大报销额
	vector<vector<int>> dp(366, vector<int>(M+1, 0));
	for(int i = 1; i <= 365; i++) {
		for(int j = 0; j <= M; j++) {
			// 情况1：不选第i天的任何票据
			dp[i][j] = dp[i-1][j];
			// 情况2：尝试选择第 i 天的某一张票据
			int prev_day = max(0, i - K); // 保证不在k天之内
			for(int v : tickets[i]) {
				if(j >= v) {
					dp[i][j] = max(dp[i][j], dp[prev_day][j - v] + v);
				}
			}
		}
	}
	cout<<dp[365][M];
	return 0;
}

/*
【总结】
1. 题型模板：日期/时间轴上选取若干票据，带“间隔 >= K”和“总额 <= M”约束时，先做时间离散/排序，再做带冷却时间的 0/1 背包。
2. 模板框架：按天汇总价值列表 -> 用 dp[day][budget] 维护前 day 天、预算不超 budget 的最大收益 -> 转移为不选当天或选当天某一张票据。
3. 复杂度结论：时间 O(D * M + N * M)（D=365），空间 O(D * M)；D 固定可接受。
4. 通用易错点：间隔约束要用 dp[day-K]，而不是 day-1；同一天有多张票据时，需遍历该天票据而非只取一张。
5. 本题特化：将月份/日期映射到 1..365 的绝对天数，注意非闰年且跨年不互相影响。
6. 本题边界：prev_day 取 max(0, i-K) 处理前 K 天无可选历史；预算上限 M 直接做上界，答案取 dp[365][M]。
*/
