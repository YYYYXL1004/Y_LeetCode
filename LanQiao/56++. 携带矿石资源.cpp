/*
题目描述
你是一名宇航员，即将前往一个遥远的行星。在这个行星上，有许多不同类型的矿石资源，
每种矿石都有不同的重要性和价值。你需要选择哪些矿石带回地球，但你的宇航舱有一定的容量限制。

给定一个宇航舱，最大容量为 C。现在有 N 种不同类型的矿石，每种矿石有一个重量 w[i]，
一个价值 v[i]，以及最多 k[i] 个可用。不同类型的矿石在地球上的市场价值不同。
你需要计算如何在不超过宇航舱容量的情况下，最大化你所能获取的总价值。

输入描述
输入共包括四行，第一行包含两个整数 C 和 N，分别表示宇航舱的容量和矿石的种类数量。
接下来的三行，每行包含 N 个正整数。
第二行包含 N 个整数，表示 N 种矿石的重量。
第三行包含 N 个整数，表示 N 种矿石的价格。
第四行包含 N 个整数，表示 N 种矿石的可用数量上限。

输出描述
输出一个整数，代表获取的最大价值。

输入示例
10 3
1 3 4
15 20 30
2 3 2

输出示例
90

提示信息
数据范围：
1 <= C <= 2000;
1 <= N <= 100;
1 <= w[i], v[i], k[i] <= 1000;
*/
#include<bits/stdc++.h>
using namespace std;

int main() {
    int C, N;  cin>>C>>N;
    vector<int> w(N);
    vector<int> v(N);
    vector<int> n(N);
    for(int i = 0; i < N; i++) cin>>w[i];
    for(int i = 0; i < N; i++) cin>>v[i];
    for(int i = 0; i < N; i++) cin>>n[i];

    // 用于存放二进制拆分后的新物品
    vector<int> weight;
    vector<int> value;
    // 二进制拆分
    for(int i = 0; i < N; i++) {
        // int cnt = n[i];
        // 按照1, 2, 4, 8..进行打包， k <<= 1 等于 k *= 2
        for(int k = 1; k <= n[i]; k <<= 1) {
            weight.push_back(w[i] * k);
            value.push_back(v[i] * k);
            n[i] -= k; // 扣除已经打包的数量
        }
        // 如果还剩余尾数，单独打包
        if(n[i] > 0) {
            weight.push_back(w[i] * n[i]);
            value.push_back(v[i] * n[i]);
        }
    }
    // 对拆分后的新物品集合，直接跑标准的 0-1 背包
    vector<int> dp(C+1, 0);
    for(int i = 0; i < (int)weight.size(); i++) {
        for(int j = C; j >= weight[i]; j--) {
            dp[j] = max(dp[j], dp[j - weight[i]] + value[i]);
        }
    }
    cout<<dp[C];

    // 方法一：直接在0/1背包基础上 加遍历n[i]次
    // vector<int> dp(C+1, 0);
    // for(int i =0; i < N; i++) {
    //     for(int j = C; j >= w[i]; j--) {
    //         // 在0/1背包基础上加一个遍历个数
    //         for(int k = 1; k <= n[i] && (j - k * w[i]) >= 0; k++) {
    //             dp[j] = max(dp[j], dp[j - k * w[i]] + k * v[i]);
    //         }
    //     }
    // }
    // cout<<dp[C];
    return 0;
}

/*
【总结】
1. 通用模板（有数量上限的背包）：当物品有上限且容量不大，优先用二进制拆分把每类物品拆成若干件 0/1 物品，再做标准 0/1 背包。
2. 通用框架：对每类物品按 1,2,4,... 拆分，剩余尾数单独成件；再用一维 dp 逆序遍历容量更新。
3. 正确性要点：二进制拆分保证每个可选数量都能由若干拆分件组合得到，等价覆盖原有上限选择。
4. 复杂度结论：拆分件数为 O(sum log k[i])，总体时间 O(C * sum log k[i])，空间 O(C)。
5. 通用易错点：容量必须逆序更新；拆分时要正确扣减剩余数量，尾数不能漏。
6. 本题差异化补充：C <= 2000、N <= 100，二进制拆分后规模可控，直接 0/1 背包即可通过。
*/