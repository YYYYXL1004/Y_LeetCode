/*
爬楼梯进阶版

题目描述
假设你正在爬楼梯。需要 n 阶你才能到达楼顶。
每次你可以爬至多 m (1 <= m < n) 个台阶。你有多少种不同的方法可以爬到楼顶呢？
注意：给定 n 是一个正整数。

输入描述
输入共一行，包含两个正整数，分别表示 n, m。

输出描述
输出一个整数，表示爬到楼顶的方法数。

输入示例
3 2

输出示例
3

提示信息
数据范围：
1 <= m < n <= 32;

当 m = 2，n = 3 时，n = 3 这表示一共有三个台阶，m = 2 代表你每次可以爬一个台阶或者两个台阶。

此时你有三种方法可以爬到楼顶。

1 阶 + 1 阶 + 1 阶
1 阶 + 2 阶
2 阶 + 1 阶
*/

#include<bits/stdc++.h>
using namespace std;

int main() {
    int n, m;  cin>>n>>m;
    // dp[i] 到n阶的方案数
    // 完全背包，外层遍历背包，内层遍历物品 类似于377组合总和IV
    vector<int> dp(n+1, 0);
    dp[0] = 1;
    for(int i = 1; i <= n; i++) {
        for(int j = 1; j <= m; j++) {
            if(i - j >= 0) dp[i] += dp[i - j];
        }
    }
    cout<<dp[n];
    return 0;
}

/*
【总结】
1. 通用模板（线性 DP 计数）
适用特征：从 0/1 到 n 的台阶，允许固定范围步长，问方案数。
标准框架：设 dp[i] 为到第 i 阶方案数，dp[0]=1，转移 dp[i]=sum_{k=1..m, i-k>=0} dp[i-k]。
复杂度结论：时间 O(n*m)，空间 O(n)；可用滚动数组降到 O(m)。
通用易错点：dp[0] 初始化为 1；循环按 i 从小到大；步长范围与边界判断别漏。

2. 本题差异化补充
m 可以大于 2，因此内层需遍历 1..m；数据范围 n<=32，int 足够但仍要注意累加。
输入只有一行 n,m；输出只需 dp[n]。
*/