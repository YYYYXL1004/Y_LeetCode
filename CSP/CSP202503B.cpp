/*
题目背景
众所周知，西西艾弗岛上的机器人喜欢吃苹果。

题目描述
机器人一天最多可以吃 m 个苹果。
一天内通过吃苹果获得的快乐值为 A0, A1, ..., Am。
如果某一天饲养员共投喂机器人 i 个苹果，则这一天机器人获得的快乐值为 Ai。
特别地 A0 = 0，快乐值不会凭空产生。

现在小 P 有 n 个苹果，要求把这 n 个苹果全部投喂给机器人，计算可以获得的最大快乐值收益。
每天可以投喂 1 到 m 个苹果，也可以理解为把 n 拆成若干个不超过 m 的正整数，最大化对应收益和。

输入格式
第一行包含两个整数 n 和 m，分别表示苹果总数和每天最大投喂量。
第二行包含 m 个整数 A1, A2, ..., Am，表示一天内投喂不同苹果数的收益。

输出格式
输出一个整数，表示投喂全部 n 个苹果能获得的最大收益。

样例 1
输入：
10 5
1 3 5 3 1
输出：
16
说明：
一种最优方案为 3, 3, 1, 3，共获得 5 + 5 + 1 + 5 = 16。
收益序列 A 不一定单调递增。

样例 2
输入：
4 3
1 60 100
输出：
120
说明：
一种最优方案为 2, 2，共获得 60 + 60 = 120。

数据范围
0 < n <= 10^4
0 < m <= 100
0 <= Ai <= 10^5
*/

#include <bits/stdc++.h>
using namespace std;

int main() {
    int n, m;
    cin >> n >> m;

    vector<int> v(m + 1);
    for (int i = 1; i <= m; i++) {
        cin >> v[i];
    }

    vector<int> dp(n + 1, 0);
    for (int i = 1; i <= m; i++) {
        for (int j = i; j <= n; j++) { // 完全背包，正序，可以重复选
            dp[j] = max(dp[j], dp[j - i] + v[i]);
        }
    }

    cout << dp[n];
    return 0;
}

/*
【总结】
1. 通用模板：看到“若干种选择可以重复使用，并且要求凑出固定总量的最大/最小收益”，优先建模为完全背包。
2. 标准状态：dp[j] 表示恰好凑出容量 j 时的最优值；枚举物品 i，再正序枚举容量 j，转移 dp[j] = max(dp[j], dp[j - w[i]] + val[i])。
3. 正序枚举容量的原因：完全背包允许同一种物品重复选择，dp[j - w[i]] 可以已经包含当前物品 i。
4. 复杂度模板：时间复杂度 O(种类数 * 总容量)，空间复杂度 O(总容量)。
5. 通用易错点：如果题目要求“恰好凑满”，初值要能区分不可达状态；本题由于每天可投喂 1 个苹果且 n > 0，所有容量都可达。
6. 本题差异：一天投喂 i 个苹果就是重量 i、价值 Ai 的物品；天数不限，所以每种投喂量可以重复使用。
7. 本题收益 A 不保证单调，不能贪心地每天尽量多投或选单日最大值，必须通过动态规划比较所有拆分方案。
8. 本题最大答案不超过 10^4 * 10^5 = 10^9，int 可存；若数据范围扩大，应改用 long long。
*/
